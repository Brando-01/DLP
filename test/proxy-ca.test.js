"use strict";
const { test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const path = require("node:path");
const { createControl } = require("../control/server");
const { temporary } = require("./helpers/fixtures.cjs");
const { publicProxyCA } = require("../lib/public-proxy-ca");
test("central distribuye únicamente CA pública a identidad individual vigente, nunca una clave privada", async t => {
  const tmp = await temporary(); t.after(tmp.cleanup);
  const pem = await fs.readFile(path.join(__dirname, "fixtures/public-test-ca.crt"), "utf8");
  const ca = path.join(tmp.root, "ca.pem"); await fs.writeFile(ca, pem);
  const credentials = { admin: "a".repeat(64), inspect: "b".repeat(64), telemetry: "c".repeat(64) };
  const control = createControl({ directory: tmp.root, credentials, proxyCaFile: ca });
  const server = control.app.listen(0, "127.0.0.1"); await new Promise(r => server.once("listening", r));
  t.after(() => new Promise(r => { server.close(r); server.closeAllConnections(); }));
  const base = `http://127.0.0.1:${server.address().port}`;
  const request = token => fetch(base + "/v1/lab/proxy-ca", { headers: { "X-DLP-Token": token } });
  assert.equal((await request("invalid")).status, 401);
  assert.equal((await request(credentials.telemetry)).status, 401);
  assert.equal((await request(credentials.inspect)).status, 403);
  const invitation = control.devices.invite({ name: "CA-TEST", platform: "win32", serverUrl: base, allowLabHttp: true }).invitation;
  const device = control.devices.enroll({ ...invitation, hostname: "windows-ficticio", platform: "win32" });
  const response = await request(device.inspectToken);
  assert.equal(response.status, 200); assert.equal(response.headers.get("x-dlp-ca-sha256"), publicProxyCA(pem).fingerprint256);
  assert.equal(await response.text(), publicProxyCA(pem).pem);
  await fs.writeFile(ca, pem + "\n-----BEGIN PRIVATE KEY-----\nNO_RETORNAR\n");
  const blocked = await request(device.inspectToken); assert.equal(blocked.status, 503); assert.ok(!(await blocked.text()).includes("NO_RETORNAR"));
  await fs.unlink(ca); assert.equal((await request(device.inspectToken)).status, 503);
  control.devices.revoke(device.deviceId); assert.equal((await request(device.inspectToken)).status, 401);
});
